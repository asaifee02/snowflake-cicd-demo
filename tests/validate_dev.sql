
EXECUTE IMMEDIATE $$
DECLARE
    VALIDATION_FAILED EXCEPTION (
        -20001,
        'DEV deployment validation failed'
    );

    V_SOURCE_ORDERS NUMBER;
    V_VIEW_ORDERS NUMBER;
    V_SOURCE_TOTAL NUMBER(18,2);
    V_VIEW_TOTAL NUMBER(18,2);
    V_DUPLICATES NUMBER;
    V_INVALID NUMBER;

BEGIN
    SELECT COUNT(*), COALESCE(SUM(AMOUNT), 0)
    INTO :V_SOURCE_ORDERS, :V_SOURCE_TOTAL
    FROM <% database %>.STAGING.SALES_CLEAN;

    SELECT
        COALESCE(SUM(TOTAL_ORDERS), 0),
        COALESCE(SUM(TOTAL_SALES), 0)
    INTO :V_VIEW_ORDERS, :V_VIEW_TOTAL
    FROM <% database %>.ANALYTICS.DAILY_SALES;

    SELECT COUNT(*)
    INTO :V_DUPLICATES
    FROM (
        SELECT ORDER_ID
        FROM <% database %>.STAGING.SALES_CLEAN
        GROUP BY ORDER_ID
        HAVING COUNT(*) > 1
    );

    SELECT COUNT(*)
    INTO :V_INVALID
    FROM <% database %>.STAGING.SALES_CLEAN
    WHERE ORDER_ID IS NULL
       OR REGION IS NULL
       OR TRIM(REGION) = ''
       OR AMOUNT IS NULL
       OR AMOUNT <= 0
       OR ORDER_DATE IS NULL;

    IF (
        V_SOURCE_ORDERS <> V_VIEW_ORDERS
        OR V_SOURCE_TOTAL <> V_VIEW_TOTAL
        OR V_DUPLICATES <> 0
        OR V_INVALID <> 0
    ) THEN
        RAISE VALIDATION_FAILED;
    END IF;

    RETURN 'PASS: DEV deployment validated';
END;
$$;
