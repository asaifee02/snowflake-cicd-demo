
-- Change this to 2 when processing the next batch.
SET BATCH_ID = 2;

MERGE INTO SALES_DEV.STAGING.SALES_CLEAN AS target
USING (
    SELECT
        TRY_TO_NUMBER(ORDER_ID)::NUMBER(10,0)
            AS ORDER_ID,
        NULLIF(TRIM(REGION), '') AS REGION,
        TRY_TO_DECIMAL(AMOUNT, 12, 2) AS AMOUNT,
        TRY_TO_DATE(ORDER_DATE, 'YYYY-MM-DD')
            AS ORDER_DATE,
        SOURCE_UPDATED_AT,
        EVENT_ID
    FROM SALES_DEV.RAW.SALES_EVENTS
    WHERE BATCH_ID = $BATCH_ID
      AND TRY_TO_NUMBER(ORDER_ID) IS NOT NULL
      AND TRY_TO_NUMBER(ORDER_ID) BETWEEN 0 AND 9999999999
      AND TRY_TO_NUMBER(ORDER_ID)
          = TRUNC(TRY_TO_NUMBER(ORDER_ID))
      AND NULLIF(TRIM(REGION), '') IS NOT NULL
      AND TRY_TO_DECIMAL(AMOUNT, 12, 2) > 0
      AND TRY_TO_DATE(ORDER_DATE, 'YYYY-MM-DD')
          IS NOT NULL
      AND SOURCE_UPDATED_AT IS NOT NULL
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY ORDER_ID
        ORDER BY SOURCE_UPDATED_AT DESC, EVENT_ID DESC
    ) = 1
) AS source

ON target.ORDER_ID = source.ORDER_ID

WHEN MATCHED
    AND source.SOURCE_UPDATED_AT > target.SOURCE_UPDATED_AT
THEN UPDATE SET
    target.REGION = source.REGION,
    target.AMOUNT = source.AMOUNT,
    target.ORDER_DATE = source.ORDER_DATE,
    target.SOURCE_UPDATED_AT = source.SOURCE_UPDATED_AT

WHEN NOT MATCHED THEN INSERT (
    ORDER_ID,
    REGION,
    AMOUNT,
    ORDER_DATE,
    SOURCE_UPDATED_AT
)
VALUES (
    source.ORDER_ID,
    source.REGION,
    source.AMOUNT,
    source.ORDER_DATE,
    source.SOURCE_UPDATED_AT
);
